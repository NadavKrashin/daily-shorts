"""Deterministic mock LLM for dry runs and tests (no network, no cost).

Looks for curated content in ``seeds/<topic-slug>/<task>.json`` first (e.g. the traffic-jam demo pack,
written and source-checked by hand). Otherwise it builds clearly-labelled placeholder content that
passes schema validation but is flagged ``is_mock`` - QC will refuse to publish anything built on it.
"""
from __future__ import annotations

import json
from datetime import date
from pathlib import Path

from waitwhy.providers.base import LLMResult, ResearchResult, SearchHit
from waitwhy.schemas import (
    EditorialReview,
    ExecutiveNarrative,
    FactSheet,
    PublishMetadata,
    ScriptDraft,
    StoryboardSpec,
    TopicBatch,
)
from waitwhy.settings import ROOT

SEEDS = ROOT / "seeds"


def _seed(slug: str | None, task: str):
    if not slug:
        return None
    p = SEEDS / slug / f"{task}.json"
    return json.loads(p.read_text()) if p.exists() else None


class MockLLM:
    name = "mock"

    def structured(self, *, task, system, prompt, schema, model, effort="medium", max_tokens=16000, context=None,
                   images=None):
        ctx = context or {}
        data = _seed(ctx.get("slug"), task)
        from_seed = data is not None
        if data is None:
            data = self._generic(task, schema, ctx)
        parsed = schema.model_validate(data)
        # Seeded packs are human-curated content, but they did not come from a live model call.
        return LLMResult(parsed=parsed, model=f"mock:{model}", is_mock=not from_seed or bool(ctx.get("force_mock")),
                         raw_text=json.dumps(data)[:2000])

    def research(self, *, system, prompt, model, effort="high", max_searches=8, context=None):
        ctx = context or {}
        data = _seed(ctx.get("slug"), "research")
        if data:
            return ResearchResult(memo=data["memo"], hits=[SearchHit(**h) for h in data["hits"]],
                                  model=f"mock:{model}", is_mock=False)
        return ResearchResult(memo=f"[MOCK] No live research performed for {ctx.get('title')}.", hits=[],
                              model=f"mock:{model}", is_mock=True)

    # ------------------------------------------------------------------ generic placeholders
    def _generic(self, task: str, schema, ctx: dict) -> dict:
        title = ctx.get("title", "Untitled topic")
        if schema is TopicBatch:
            pool = json.loads((SEEDS / "topics.json").read_text())["topics"]
            existing = set(ctx.get("existing_slugs", []))
            fresh = [t for t in pool if t["slug"] not in existing][: ctx.get("count", 10)]
            for t in fresh:
                t.pop("slug", None)
            return {"candidates": fresh}
        if schema is FactSheet:
            today = date.today().isoformat()
            return {
                "topic": title, "core_explanation": f"[MOCK] Placeholder explanation for {title}.",
                "claims": [{"id": "C1", "text": f"[MOCK] Central claim about {title}.", "importance": "central",
                            "status": "verified", "source_ids": ["S1", "S2"], "notes": "mock"}],
                "sources": [
                    {"id": "S1", "url": "https://example.org/mock-source-1", "title": "Mock source 1",
                     "publisher": "Mock Publisher A", "source_type": "secondary", "accessed_on": today,
                     "key_excerpt": "mock"},
                    {"id": "S2", "url": "https://example.org/mock-source-2", "title": "Mock source 2",
                     "publisher": "Mock Publisher B", "source_type": "secondary", "accessed_on": today,
                     "key_excerpt": "mock"}],
                "uncertainties": ["[MOCK] not researched"], "misleading_simplifications": [],
                "safe_analogies": [], "risk_level": "standard", "risk_reasons": [], "verdict": "verified",
            }
        if schema is ScriptDraft:
            words = ("This sentence is placeholder narration generated by the mock language model for testing "
                     "the pipeline end to end without any paid API calls at all.").split()
            beats = ["hook", "mystery", "setup", "explanation", "explanation", "reveal", "conclusion"]
            segs = [{"beat": b, "text": " ".join(words[: 18 + (i % 3)]) + ".", "claim_ids": ["C1"] if i == 3 else [],
                     "visual_intent": f"{b} visual"} for i, b in enumerate(beats)]
            return {"title": f"[MOCK] {title}", "alt_hooks": ["[MOCK] hook A", "[MOCK] hook B", "[MOCK] hook C"],
                    "chosen_hook_index": 0, "hook_style": "question", "story_structure": "classic-6-beat",
                    "segments": segs, "conclusion": segs[-1]["text"], "why_compelling": "[MOCK]",
                    "scores": {"clarity": 50, "originality": 50, "accuracy": 50, "pacing": 50, "hook_strength": 50}}
        if schema is StoryboardSpec:
            segs = ctx.get("segments") or []
            scenes, t = [], 0.0
            n = max(8, min(12, len(segs) or 8))
            for i in range(n):
                seg = segs[i] if i < len(segs) else {"beat": "explanation", "text": ""}
                dur = 6.0
                tpl = "title_card" if i == 0 else ("end_card" if i == n - 1 else "kinetic_text")
                scenes.append({
                    "scene_number": i + 1, "beat": seg["beat"], "narration": seg["text"], "start_s": t,
                    "end_s": t + dur, "visual_description": "[MOCK] text-driven motion graphic",
                    "camera_angle": "front", "camera_movement": "slow push", "main_objects": ["text"],
                    "behavior": "words animate in", "color_direction": "brand palette",
                    "animation_motion": "ease-out pop", "on_screen_text": seg["text"][:40],
                    "sound_effects": [], "transition": "crossfade", "render_method": "programmatic",
                    "template": tpl, "template_params": [{"key": "headline", "value": json.dumps(title[:40])}],
                    "generation_prompt": "", "negative_prompt": "", "continuity": ["brand palette"],
                })
                t += dur
            return {"title": title, "style": {"look": "flat", "lighting": "flat", "palette": [],
                    "camera_geography": "n/a", "typography": "Inter"}, "recurring_objects": [], "scenes": scenes}
        if schema is PublishMetadata:
            return {"youtube_title_candidates": [f"{title}?", f"Why {title}", f"The truth about {title}"],
                    "youtube_title": title[:90], "youtube_description": f"{title}. [MOCK description]",
                    "instagram_caption": f"{title} [MOCK]", "tiktok_caption": f"{title} [MOCK]",
                    "facebook_caption": f"{title} [MOCK]", "hashtags": ["#science", "#explained"],
                    "call_to_action": "Follow for more", "cover_text": title[:30],
                    "disclosure": {"ai_generated_visuals": False, "realistic_synthetic_media": False,
                                   "paid_promotion": False, "notes": "mock"}}
        if schema is EditorialReview:
            return {"narration_matches_visuals": True, "unsupported_claims": [], "continuity_problems": [],
                    "clarity_issues": [], "brand_issues": [],
                    "viewer_experience_notes": "[MOCK] no multimodal review performed", "scores": {}}
        if schema is ExecutiveNarrative:
            return {"summary": "[MOCK] narrative not generated (no LLM configured).", "inferences": [],
                    "recommendations": []}
        raise NotImplementedError(f"mock has no generic builder for {schema.__name__}")
